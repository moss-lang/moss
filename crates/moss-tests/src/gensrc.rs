//! Generators for the Moss sources that are tables.
//!
//! Five files are mechanical: three under `src/` — the spelling of every
//! string the compiler must hold itself (D48), the token kinds as Ints,
//! and the `Wasm` context as an opcode table — and two under `lib/`, the
//! char constants and their values over `Wasm`. Writing any of them by
//! hand is a typo per character, so they are generated here, written by
//! `cargo run -p moss-tests --bin gensrc`, and checked against disk by the
//! suite's `gensrc` tests. Ported from the Python bootstrap's
//! `mossc/gensrc.py` and `mossc/native.py`, output for output.

use std::fs;

use crate::repo;

/// The char constants: name, character.
pub fn chars() -> Vec<(String, char)> {
    let mut out = Vec::new();
    for c in ('a'..='z').chain('A'..='Z') {
        out.push((c.to_string(), c));
    }
    for i in 0..10 {
        out.push((format!("digit{i}"), char::from(b'0' + i)));
    }
    for (name, c) in [
        ("exclam", '!'),
        ("percent", '%'),
        ("ampersand", '&'),
        ("lparen", '('),
        ("rparen", ')'),
        ("star", '*'),
        ("plus", '+'),
        ("comma", ','),
        ("hyphen", '-'),
        ("dot", '.'),
        ("slash", '/'),
        ("colon", ':'),
        ("semi", ';'),
        ("less", '<'),
        ("equal", '='),
        ("greater", '>'),
        ("lbracket", '['),
        ("rbracket", ']'),
        ("caret", '^'),
        ("lbrace", '{'),
        ("pipe", '|'),
        ("rbrace", '}'),
        ("space", ' '),
        ("newline", '\n'),
        ("tab", '\t'),
        ("cr", '\r'),
        ("underscore", '_'),
        ("quote", '"'),
        ("apostrophe", '\''),
        ("octothorpe", '#'),
        ("backslash", '\\'),
        ("question", '?'),
        ("at", '@'),
        ("dollar", '$'),
        ("backtick", '`'),
        ("tilde", '~'),
    ] {
        out.push((name.to_string(), c));
    }
    out
}

/// The `char::` constant for a character of a name: the ones that are not
/// their own name.
fn char_name(c: char) -> String {
    match c {
        '_' => "underscore".into(),
        '.' => "dot".into(),
        '0'..='9' => format!("digit{c}"),
        _ => c.to_string(),
    }
}

