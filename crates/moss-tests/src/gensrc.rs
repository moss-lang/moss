pub fn gen_spell_moss() -> String {
    let mut out = vec![format!(
        "import \"./bytes.moss\" use push_char;

# The strings the compiler must hold itself.
#
# A Wasm module names its imports and exports in its own bytes, so an
# emitter cannot avoid knowing how `wasi_snapshot_preview1` is spelled,
# and the back end cannot recognize `I32` or `i32_bool` without knowing
# how those are spelled either. There are no string literals (D48), so
# each one is written character by character against the `char`
# constants — the same technique the lexer's keyword trie uses to
# recognize keywords without literals. This is the whole of what D48
# costs the back end: one function per name, and no name the compiler
# does not already need appears here.
#
{SRC_HEADER}

assume Std {{"
    )];
    for name in SPELLED {
        let function = format!("sp_{}", name.replace('.', "_").trim_start_matches('_'));
        let pushes: Vec<String> = name
            .chars()
            .map(|c| format!("    push_char(out, char::{});", char_name(c)))
            .collect();
        out.push(format!("  fn {function}(out: IntList) {{\n{}\n  }}\n", pushes.join("\n")));
    }
    out.push("}".into());
    out.join("\n") + "\n"
}

// --- src/tcode.moss ----------------------------------------------------

fn snake(name: &str) -> String {
    match name {
        "LParen" => return "lparen".into(),
        "RParen" => return "rparen".into(),
        "LBracket" => return "lbracket".into(),
        "RBracket" => return "rbracket".into(),
        "LBrace" => return "lbrace".into(),
        "RBrace" => return "rbrace".into(),
        "ThisType" => return "this_type".into(),
        "ThisValue" => return "this_value".into(),
        _ => {}
    }
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if i > 0 && c.is_ascii_uppercase() {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}

/// The members of `type Token = ...;` in `src/lex.moss`, in order.
pub fn token_names() -> Vec<String> {
    let source = fs::read_to_string(repo().join("src/lex.moss")).expect("src/lex.moss");
    let start = source.find("type Token =").expect("`type Token =` in src/lex.moss") + "type Token =".len();
    let end = start + source[start..].find(';').expect("the end of `type Token`");
    source[start..end]
        .split('|')
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .map(String::from)
        .collect()
}

pub fn gen_tcode_moss() -> String {
    let names = token_names();
    let mut out = vec![format!(
        "import \"./bytes.moss\" use *;
import \"./lex.moss\" use Token;
import \"./token.moss\" use *;

# Token kinds as Ints.
#
# `Token` is a union of sixty units, which is the right type for the
# lexer to return and the wrong one for a recursive-descent parser to
# carry: a parser compares the current token against a handful of
# expected ones per production, and a match arm per comparison is
# unreadable. The cursor holds an Int instead, converted here once per
# token.
#
{SRC_HEADER}

assume Std {{"
    )];
    for (i, name) in names.iter().enumerate() {
        out.push(format!("  fn tk_{}(): Int {{ {i} }}", snake(name)));
    }
    out.push(String::new());
    out.push("  fn token_code(t: Token): Int {".into());
    out.push("    match t {".into());
    for name in &names {
        out.push(format!("      {name} => tk_{}(),", snake(name)));
    }
    out.push("    }".into());
    out.push("  }".into());
    out.push("}".into());
    out.join("\n") + "\n"
}

