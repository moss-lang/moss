/// How an intrinsic encodes.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    Simple,
    Memarg,
    Const0,
    Const1,
    MemZero,
    MemCopy,
    MemFill,
    Prefixed,
}

/// What it leaves on the stack.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Res {
    None,
    I32,
    I64,
    F32,
    F64,
}

impl Kind {
    fn function(self) -> &'static str {
        match self {
            Kind::Simple => "wk_simple()",
            Kind::Memarg => "wk_memarg()",
            Kind::Const0 => "wk_const0()",
            Kind::Const1 => "wk_const1()",
            Kind::MemZero => "wk_memzero()",
            Kind::MemCopy => "wk_memcopy()",
            Kind::MemFill => "wk_memfill()",
            Kind::Prefixed => "wk_prefixed()",
        }
    }
}

impl Res {
    fn function(self) -> &'static str {
        match self {
            Res::None => "wr_none()",
            Res::I32 => "wr_i32()",
            Res::I64 => "wr_i64()",
            Res::F32 => "wr_f32()",
            Res::F64 => "wr_f64()",
        }
    }
}

/// One `Wasm` item: its name, opcode, encoding, alignment (a prefixed
/// instruction's sub-opcode) and result.
#[derive(Clone, Debug)]
pub struct Op {
    pub name: String,
    pub code: u32,
    pub kind: Kind,
    pub align: u32,
    pub res: Res,
}

/// The `Wasm` context's instructions, in table order.
pub fn wasm_ops() -> Vec<Op> {
    let mut ops: Vec<Op> = Vec::new();
    let mut add = |name: &str, code: u32, kind: Kind, align: u32, res: Res| {
        ops.push(Op {
            name: name.to_string(),
            code,
            kind,
            align,
            res,
        });
    };
    use Kind::*;
    add("unreachable", 0x00, Simple, 0, Res::None);
    add("i32_zero", 0, Const0, 0, Res::I32);
    add("i32_one", 0, Const1, 0, Res::I32);
    for (name, code, align, res) in [
        ("i32_load", 0x28, 2, Res::I32),
        ("i64_load", 0x29, 3, Res::I64),
        ("i32_load8_s", 0x2C, 0, Res::I32),
        ("i32_load8_u", 0x2D, 0, Res::I32),
        ("i32_load16_s", 0x2E, 1, Res::I32),
        ("i32_load16_u", 0x2F, 1, Res::I32),
        ("i64_load8_s", 0x30, 0, Res::I64),
        ("i64_load8_u", 0x31, 0, Res::I64),
        ("i64_load16_s", 0x32, 1, Res::I64),
        ("i64_load16_u", 0x33, 1, Res::I64),
        ("i64_load32_s", 0x34, 2, Res::I64),
        ("i64_load32_u", 0x35, 2, Res::I64),
        ("i32_store", 0x36, 2, Res::None),
        ("i64_store", 0x37, 3, Res::None),
        ("i32_store8", 0x3A, 0, Res::None),
        ("i32_store16", 0x3B, 1, Res::None),
        ("i64_store8", 0x3C, 0, Res::None),
        ("i64_store16", 0x3D, 1, Res::None),
        ("i64_store32", 0x3E, 2, Res::None),
    ] {
        add(name, code, Memarg, align, res);
    }
    add("memory_size", 0x3F, MemZero, 0, Res::I32);
    add("memory_grow", 0x40, MemZero, 0, Res::I32);
    add("memory_copy", 0xFC, MemCopy, 0, Res::None);
    add("memory_fill", 0xFC, MemFill, 0, Res::None);
    let comparisons = "eqz eq ne lt_s lt_u gt_s gt_u le_s le_u ge_s ge_u";
    for (i, name) in comparisons.split(' ').enumerate() {
        add(&format!("i32_{name}"), 0x45 + i as u32, Simple, 0, Res::I32);
        // A comparison yields an i32.
        add(&format!("i64_{name}"), 0x50 + i as u32, Simple, 0, Res::I32);
    }
    let arithmetic =
        "clz ctz popcnt add sub mul div_s div_u rem_s rem_u and or xor shl shr_s shr_u rotl rotr";
    for (i, name) in arithmetic.split(' ').enumerate() {
        add(&format!("i32_{name}"), 0x67 + i as u32, Simple, 0, Res::I32);
        add(&format!("i64_{name}"), 0x79 + i as u32, Simple, 0, Res::I64);
    }
    add("i32_extend8_s", 0xC0, Simple, 0, Res::I32);
    add("i32_extend16_s", 0xC1, Simple, 0, Res::I32);
    add("i64_extend8_s", 0xC2, Simple, 0, Res::I64);
    add("i64_extend16_s", 0xC3, Simple, 0, Res::I64);
    add("i64_extend32_s", 0xC4, Simple, 0, Res::I64);
    add("i32_wrap_i64", 0xA7, Simple, 0, Res::I32);
    add("i64_extend_i32_s", 0xAC, Simple, 0, Res::I64);
    add("i64_extend_i32_u", 0xAD, Simple, 0, Res::I64);
    // The float half (D67). A prefixed instruction keeps its sub-opcode
    // where a memory access keeps its alignment.
    for (name, code, align, res) in [
        ("f32_load", 0x2A, 2, Res::F32),
        ("f64_load", 0x2B, 3, Res::F64),
        ("f32_store", 0x38, 2, Res::None),
        ("f64_store", 0x39, 3, Res::None),
    ] {
        add(name, code, Memarg, align, res);
    }
    for (i, name) in "eq ne lt gt le ge".split(' ').enumerate() {
        add(&format!("f32_{name}"), 0x5B + i as u32, Simple, 0, Res::I32);
        add(&format!("f64_{name}"), 0x61 + i as u32, Simple, 0, Res::I32);
    }
    let float_arithmetic = "abs neg ceil floor trunc nearest sqrt add sub mul div min max copysign";
    for (i, name) in float_arithmetic.split(' ').enumerate() {
        add(&format!("f32_{name}"), 0x8B + i as u32, Simple, 0, Res::F32);
        add(&format!("f64_{name}"), 0x99 + i as u32, Simple, 0, Res::F64);
    }
    // The conversions, in opcode order.
    for (name, code, res) in [
        ("i32_trunc_f32_s", 0xA8, Res::I32),
        ("i32_trunc_f32_u", 0xA9, Res::I32),
        ("i32_trunc_f64_s", 0xAA, Res::I32),
        ("i32_trunc_f64_u", 0xAB, Res::I32),
        ("i64_trunc_f32_s", 0xAE, Res::I64),
        ("i64_trunc_f32_u", 0xAF, Res::I64),
        ("i64_trunc_f64_s", 0xB0, Res::I64),
        ("i64_trunc_f64_u", 0xB1, Res::I64),
        ("f32_convert_i32_s", 0xB2, Res::F32),
        ("f32_convert_i32_u", 0xB3, Res::F32),
        ("f32_convert_i64_s", 0xB4, Res::F32),
        ("f32_convert_i64_u", 0xB5, Res::F32),
        ("f32_demote_f64", 0xB6, Res::F32),
        ("f64_convert_i32_s", 0xB7, Res::F64),
        ("f64_convert_i32_u", 0xB8, Res::F64),
        ("f64_convert_i64_s", 0xB9, Res::F64),
        ("f64_convert_i64_u", 0xBA, Res::F64),
        ("f64_promote_f32", 0xBB, Res::F64),
        ("i32_reinterpret_f32", 0xBC, Res::I32),
        ("i64_reinterpret_f64", 0xBD, Res::I64),
        ("f32_reinterpret_i32", 0xBE, Res::F32),
        ("f64_reinterpret_i64", 0xBF, Res::F64),
    ] {
        add(name, code, Simple, 0, res);
    }
    // The saturating truncations: 0xFC, then this sub-opcode as a LEB.
    for (i, (name, res)) in [
        ("i32_trunc_sat_f32_s", Res::I32),
        ("i32_trunc_sat_f32_u", Res::I32),
        ("i32_trunc_sat_f64_s", Res::I32),
        ("i32_trunc_sat_f64_u", Res::I32),
        ("i64_trunc_sat_f32_s", Res::I64),
        ("i64_trunc_sat_f32_u", Res::I64),
        ("i64_trunc_sat_f64_s", Res::I64),
        ("i64_trunc_sat_f64_u", Res::I64),
    ]
    .into_iter()
    .enumerate()
    {
        add(name, 0xFC, Prefixed, i as u32, res);
    }
    ops
}

pub fn gen_wasmops_moss() -> String {
    let mut out = vec![format!(
        "import \"./bytes.moss\" use *;
import \"./intern.moss\" as intern;

# The `Wasm` context, as a table the back end can match a callee against.
#
# A call to one of these compiles to an instruction rather than to a call
# (D52). Each name is built as bytes and interned once, after which a lookup
# compares interned ids. This generated table retains character appends:
# quoted byte lowering currently makes its large installer costly to optimize.
# The opcodes are the Wasm specification's.
#
{SRC_HEADER}

assume Std {{
  # How an intrinsic encodes.
  fn wk_simple(): Int {{ 0 }}
  fn wk_memarg(): Int {{ 1 }}
  fn wk_const0(): Int {{ 2 }}
  fn wk_const1(): Int {{ 3 }}
  fn wk_memzero(): Int {{ 4 }}
  fn wk_memcopy(): Int {{ 5 }}
  fn wk_memfill(): Int {{ 6 }}
  fn wk_prefixed(): Int {{ 7 }}

  # What it leaves on the stack.
  fn wr_none(): Int {{ 0 }}
  fn wr_i32(): Int {{ 1 }}
  fn wr_i64(): Int {{ 2 }}
  fn wr_f32(): Int {{ 3 }}
  fn wr_f64(): Int {{ 4 }}

  val op_names: IntList;
  val op_codes: IntList;
  val op_kinds: IntList;
  val op_aligns: IntList;
  val op_res: IntList;

  context WasmOps = op_names, op_codes, op_kinds, op_aligns, op_res;

  assume WasmOps, intern::Interner {{
    fn add_op(cs: IntList, code: Int, kind: Int, align: Int, res: Int) {{
      op_names.push(intern::intern_chars(cs));
      op_codes.push(code);
      op_kinds.push(kind);
      op_aligns.push(align);
      op_res.push(res);
    }}

    # The table's index for this interned name, or none.
    fn find_op(name: Int): Int {{
      var i = 0;
      while i < op_names.length() {{
        if op_names.get(i) == name {{
          return i;
        }}
        i = i + 1;
      }}
      -1
    }}

    fn install_wasm_ops() {{"
    )];
    for op in wasm_ops() {
        let buf = format!("b_{}", op.name);
        let pushes: String = op
            .name
            .chars()
            .map(|c| format!(" push_char({buf}, char::{});", char_name(c)))
            .collect();
        out.push(format!(
            "      let {buf} = int_list();{pushes} add_op({buf}, {}, {}, {}, {});",
            op.code,
            op.kind.function(),
            op.align,
            op.res.function()
        ));
    }
    out.push("    }".into());
    out.push("  }".into());
    out.push("}".into());
    out.join("\n") + "\n"
}

// --- lib/char.moss and lib/wasichar.moss ------------------------------

pub fn gen_char_moss() -> String {
    let chars = chars();
    let mut lines: Vec<String> = vec![
        "# Generated by `cargo run -p moss-tests --bin gensrc`, from the list in".into(),
        "# crates/moss-tests/src/gensrc.rs; regenerate rather than edit.".into(),
        String::new(),
        "import \"./int.moss\" use Int;".into(),
        "import \"./num.moss\" use .eq, .ne, .lt, .gt, .le, .ge;".into(),
        String::new(),
        "type Char;".into(),
        String::new(),
        "assume Char {".into(),
    ];
    for (name, _) in &chars {
        lines.push(format!("  val {name}: Char;"));
    }
    lines.extend(
        [
            "",
            "  assume Int {",
            "    # Char <-> Int, so text can be stored as codepoints",
            "    # rather than as spans into one source buffer. Both are",
            "    # detached, so the receiver is whichever this module's",
            "    # importer provides them at: `Char.code` and `Int.char`.",
            "    fn .code(): Int;",
            "    fn .char(): Char;",
            "  }",
            "",
            "  context Chars =",
        ]
        .map(String::from),
    );
    for method in ["eq", "ne", "lt", "gt", "le", "ge"] {
        lines.push(format!("    Char.{method},"));
    }
    for (name, _) in &chars {
        lines.push(format!("    {name},"));
    }
    lines.push("  ;".into());
    lines.push("}".into());
    lines.push(String::new());
    lines.join("\n")
}

/// The char constants, provided over `Wasm`, each codepoint an or of
/// powers of two built from `i32_one`.
pub fn gen_wasichar_moss() -> String {
    let mut lines: Vec<String> = [
        "# Generated by `cargo run -p moss-tests --bin gensrc`, from the list in",
        "# crates/moss-tests/src/gensrc.rs; regenerate rather than edit.",
        "",
        "import \"./wasm.moss\" as w use Wasm, I32;",
        "import \"./char.moss\" as char use Char;",
        "import \"./wasistd.moss\" use Chr;",
        "",
        "assume Wasm {",
        "  # Shift amounts, built from `i32_one` like everything else.",
        "  fn n1(): I32 { w::i32_one }",
        "  fn n2(): I32 { w::i32_add(n1(), n1()) }",
        "  fn n3(): I32 { w::i32_add(n2(), n1()) }",
        "  fn n4(): I32 { w::i32_add(n2(), n2()) }",
        "  fn n5(): I32 { w::i32_add(n4(), n1()) }",
        "  fn n6(): I32 { w::i32_add(n4(), n2()) }",
        "",
        "  fn bit(k: I32): I32 { w::i32_shl(w::i32_one, k) }",
        "",
    ]
    .map(String::from)
    .to_vec();
    let expr = |code: u32| -> String {
        let terms: Vec<String> = (0..7)
            .filter(|k| code >> k & 1 == 1)
            .map(|k| {
                if k == 0 {
                    "w::i32_one".to_string()
                } else {
                    format!("bit(n{k}())")
                }
            })
            .collect();
        let mut out = terms[0].clone();
        for term in &terms[1..] {
            out = format!("w::i32_or({out}, {term})");
        }
        out
    };
    let chars = chars();
    for (name, value) in &chars {
        lines.push(format!(
            "  fn char_{name}(): Chr {{ Chr({}) }}",
            expr(*value as u32)
        ));
    }
    lines.push("}".into());
    lines.push(String::new());
    lines.push("context WasiChars =".into());
    for (name, _) in &chars {
        lines.push(format!("  char::{name},"));
    }
    lines.push(";".into());
    lines.push(String::new());
    lines.push("functor WasiCharConsts: Wasm -> WasiChars {".into());
    for (name, _) in &chars {
        lines.push(format!("  bind char::{name} = char_{name}();"));
    }
    lines.push("}".into());
    lines.push(String::new());
    lines.join("\n")
}

/// All byte values, with stable hexadecimal names independent of `Int`.
pub fn bytes() -> Vec<(String, u8)> {
    (0u16..256).map(|n| (format!("x{n:02x}"), n as u8)).collect()
}

pub const BYTE_CLASSES: [&str; 12] = [
    "Ascii", "Cont808F", "Cont909F", "ContA0BF", "Lead2", "LeadE0",
    "LeadE1EC_EEEF", "LeadED", "LeadF0", "LeadF1F3", "LeadF4", "Invalid",
];

/// Smallest public range class containing this byte.
pub fn byte_class(value: u8) -> &'static str {
    match value {
        0x00..=0x7f => "Ascii",
        0x80..=0x8f => "Cont808F",
        0x90..=0x9f => "Cont909F",
        0xa0..=0xbf => "ContA0BF",
        0xc2..=0xdf => "Lead2",
        0xe0 => "LeadE0",
        0xe1..=0xec | 0xee..=0xef => "LeadE1EC_EEEF",
        0xed => "LeadED",
        0xf0 => "LeadF0",
        0xf1..=0xf3 => "LeadF1F3",
        0xf4 => "LeadF4",
        _ => "Invalid",
    }
}

pub fn gen_byte_moss() -> String {
    let mut lines = vec![SRC_HEADER.into(), String::new(),
        "# Nominal ranges with opaque payloads constrain UTF-8 scalar writes.".into()];
    for class in BYTE_CLASSES {
        lines.push(format!("type {class}Rep;"));
        lines.push(format!("assume {class}Rep {{ tag {class}({class}Rep); }}"));
    }
    lines.extend([String::new(), format!("context ByteTypes = {};", BYTE_CLASSES.iter().map(|class| format!("{class}Rep")).collect::<Vec<_>>().join(", ")),
        String::new(), "assume ByteTypes {".into(),
        "  type Continuation = Cont808F | Cont909F | ContA0BF;".into(),
        "  type ContLow = Cont808F | Cont909F;".into(),
        "  type ContHigh = Cont909F | ContA0BF;".into(),
        format!("  type Byte = {};", BYTE_CLASSES.join(" | ")),
        String::new()]);
    for (name, value) in bytes() {
        lines.push(format!("  val {name}: {};", byte_class(value)));
    }
    lines.push(String::new());
    lines.push("  context Bytes =".into());
    for (name, _) in bytes() {
        lines.push(format!("    {name},"));
    }
    lines.extend([
        "  ;", "",
        "  tag ThreeE0 { lead: LeadE0, second: ContA0BF };",
        "  tag ThreeOrdinary { lead: LeadE1EC_EEEF, second: Continuation };",
        "  tag ThreeED { lead: LeadED, second: ContLow };",
        "  type Prefix3 = ThreeE0 | ThreeOrdinary | ThreeED;", "",
        "  tag FourF0 { lead: LeadF0, second: ContHigh };",
        "  tag FourMiddle { lead: LeadF1F3, second: Continuation };",
        "  tag FourF4 { lead: LeadF4, second: Cont808F };",
        "  type Prefix4 = FourF0 | FourMiddle | FourF4;",
        "}", "",
    ].into_iter().map(String::from));
    lines.join("\n")
}

/// Independent Wasm range representations. Distinct nominal wrappers preserve
/// the public range distinctions; constants never use the language's `Int`.
pub fn gen_wasibyte_moss() -> String {
    let mut lines: Vec<String> = [
        SRC_HEADER, "",
        "import \"./wasm.moss\" as w use Wasm, I32;",
        "import \"./byte.moss\" as byte use ByteTypes, Bytes,",
    ].into_iter().map(String::from).collect();
    lines.push(format!("  {};", BYTE_CLASSES.iter().map(|class| format!("{class}Rep")).collect::<Vec<_>>().join(", ")));
    lines.extend(["", "assume Wasm {"].into_iter().map(String::from));
    for class in BYTE_CLASSES {
        lines.push(format!("  tag Octet{class}(I32);"));
    }
    for class in BYTE_CLASSES {
        lines.push(format!("  type Raw{class} = byte::{class}[{class}Rep=Octet{class}];"));
    }
    lines.extend([
        "",
        "  type RawContinuation = RawCont808F | RawCont909F | RawContA0BF;",
        "  type RawPrefix3 = byte::Prefix3[LeadE0Rep=OctetLeadE0, LeadE1EC_EEEFRep=OctetLeadE1EC_EEEF, LeadEDRep=OctetLeadED, Cont808FRep=OctetCont808F, Cont909FRep=OctetCont909F, ContA0BFRep=OctetContA0BF];",
        "  type RawPrefix4 = byte::Prefix4[LeadF0Rep=OctetLeadF0, LeadF1F3Rep=OctetLeadF1F3, LeadF4Rep=OctetLeadF4, Cont808FRep=OctetCont808F, Cont909FRep=OctetCont909F, ContA0BFRep=OctetContA0BF];",
        "",
        "  fn ascii_raw(value: RawAscii): I32 { match value { byte::Ascii(rep) => match rep { OctetAscii(raw) => raw } } }",
        "  fn lead2_raw(value: RawLead2): I32 { match value { byte::Lead2(rep) => match rep { OctetLead2(raw) => raw } } }",
        "  fn continuation_raw(value: RawContinuation): I32 {",
        "    match value {",
        "      byte::Cont808F(rep) => match rep { OctetCont808F(raw) => raw },",
        "      byte::Cont909F(rep) => match rep { OctetCont909F(raw) => raw },",
        "      byte::ContA0BF(rep) => match rep { OctetContA0BF(raw) => raw },",
        "    }",
        "  }",
        "  fn prefix3_lead(prefix: RawPrefix3): I32 {",
        "    match prefix {",
        "      byte::ThreeE0 { lead, second = _ } => match lead { byte::LeadE0(rep) => match rep { OctetLeadE0(raw) => raw } },",
        "      byte::ThreeOrdinary { lead, second = _ } => match lead { byte::LeadE1EC_EEEF(rep) => match rep { OctetLeadE1EC_EEEF(raw) => raw } },",
        "      byte::ThreeED { lead, second = _ } => match lead { byte::LeadED(rep) => match rep { OctetLeadED(raw) => raw } },",
        "    }",
        "  }",
        "  fn prefix3_second(prefix: RawPrefix3): I32 {",
        "    match prefix {",
        "      byte::ThreeE0 { lead = _, second } => continuation_raw(second),",
        "      byte::ThreeOrdinary { lead = _, second } => continuation_raw(second),",
        "      byte::ThreeED { lead = _, second } => continuation_raw(second),",
        "    }",
        "  }",
        "  fn prefix4_lead(prefix: RawPrefix4): I32 {",
        "    match prefix {",
        "      byte::FourF0 { lead, second = _ } => match lead { byte::LeadF0(rep) => match rep { OctetLeadF0(raw) => raw } },",
        "      byte::FourMiddle { lead, second = _ } => match lead { byte::LeadF1F3(rep) => match rep { OctetLeadF1F3(raw) => raw } },",
        "      byte::FourF4 { lead, second = _ } => match lead { byte::LeadF4(rep) => match rep { OctetLeadF4(raw) => raw } },",
        "    }",
        "  }",
        "  fn prefix4_second(prefix: RawPrefix4): I32 {",
        "    match prefix {",
        "      byte::FourF0 { lead = _, second } => continuation_raw(second),",
        "      byte::FourMiddle { lead = _, second } => continuation_raw(second),",
        "      byte::FourF4 { lead = _, second } => continuation_raw(second),",
        "    }",
        "  }", "",
        "  fn n1(): I32 { w::i32_one }",
        "  fn n2(): I32 { w::i32_add(n1(), n1()) }",
        "  fn n3(): I32 { w::i32_add(n2(), n1()) }",
        "  fn n4(): I32 { w::i32_add(n2(), n2()) }",
        "  fn n5(): I32 { w::i32_add(n4(), n1()) }",
        "  fn n6(): I32 { w::i32_add(n4(), n2()) }",
        "  fn n7(): I32 { w::i32_add(n4(), n3()) }",
        "  fn bit(k: I32): I32 { w::i32_shl(w::i32_one, k) }", "",
    ].into_iter().map(String::from));
    for (name, code) in bytes() {
        let terms: Vec<String> = (0..8).filter(|k| code >> k & 1 == 1)
            .map(|k| if k == 0 { "w::i32_one".into() } else { format!("bit(n{k}())") }).collect();
        let mut expr = terms.first().cloned().unwrap_or_else(|| "w::i32_zero".into());
        for term in terms.iter().skip(1) {
            expr = format!("w::i32_or({expr}, {term})");
        }
        let class = byte_class(code);
        lines.push(format!("  fn byte_{name}(): Raw{class} {{ byte::{class}[{class}Rep=Octet{class}](Octet{class}({expr})) }}"));
    }
    lines.extend(["}".into(), String::new(),
        "functor WasiByteTypes: Wasm -> ByteTypes {".into()]);
    for class in BYTE_CLASSES {
        lines.push(format!("  bind byte::{class}Rep = Octet{class};"));
    }
    lines.extend(["}".into(), String::new(),
        "functor WasiByteConsts: Wasm -> ByteTypes, Bytes {".into(),
        "  bind WasiByteTypes;".into()]);
    for (name, _) in bytes() {
        lines.push(format!("  bind byte::{name} = byte_{name}();"));
    }
    lines.extend(["}".into(), String::new()]);
    lines.join("\n")
}

