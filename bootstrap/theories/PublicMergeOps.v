Global Instance merge_eq_proper M : Proper (MergeEq M ==> MergeEq M ==> iff) (MergeEq M).
Proof.
  intros x x' X y y' Y. split; intro E.
  - eapply METrans; [apply MESym; exact X | eapply METrans; eassumption].
  - eapply METrans; [exact X | eapply METrans; [exact E | apply MESym; exact Y]].
Qed.

Global Instance merge_read_proper M N s (R : Respects M s N) :
  Proper (MergeEq M ==> MergeEq N) (app_subst s).
Proof. intros x y E. eapply merge_eq_substitute; eassumption. Qed.

Global Instance key_eq_proper M (S : Solved M) :
  Proper (KeyEq M ==> KeyEq M ==> iff) (KeyEq M).
Proof.
  intros x x' X y y' Y. destruct (solved_has_section S) as [s Section].
  apply (section_key_eq Section) in X, Y.
  rewrite !(section_key_eq Section). rewrite X, Y. reflexivity.
Qed.

