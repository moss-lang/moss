Global Instance ilookM_proper A M (S : Solved M) :
  Proper (KeyEq M ==> eq ==> eq) (@ilookM A M).
Proof. intros x y E l l' <-. now apply ilookM_key. Qed.

Global Instance mlookM_proper A M (S : Solved M) :
  Proper (MergeEq M ==> eq ==> eq ==> eq) (@mlookM A M).
Proof.
  intros t u E m m' <- l l' <-. induction l as [|[[r n] a] rest IH]; [reflexivity |].
  cbn [mlookM].
  assert (B : merge_eqb M t r = merge_eqb M u r).
  { apply eq_true_iff_eq. rewrite !(merge_eqb_spec S).
    now rewrite E. }
  rewrite B. destruct (Nat.eqb m n && merge_eqb M u r); assumption || reflexivity.
Qed.

Global Instance providesM_proper M C (S : Solved M) :
  Proper (KeyEq M ==> iff) (providesM M C).
Proof.
  intros x y E. destruct x, y; cbn [KeyEq provision_id] in E;
    try discriminate; try solve [inversion E; reflexivity].
  destruct E as [-> E]. cbn [providesM]. rewrite (mlookM_proper S E eq_refl eq_refl). reflexivity.
Qed.

Lemma expand_related : forall M t u, MergeEq M t u -> MergeEq M (expand M t) (expand M u).
Proof.
  intros M t u E. eapply METrans; [apply MESym, expand_mergeeq |].
  eapply METrans; [exact E | apply expand_mergeeq].
Qed.

Lemma expand_members : forall M t u, Solved M -> MergeEq M t u ->
  Forall2 (MergeEq M) (members (expand M t)) (members (expand M u)).
Proof.
  intros M t u S E.
  pose proof (expand_outer S E) as O.
  pose proof (expand_children S E) as C.
  pose proof (expand_related E) as R.
  destruct (expand M t), (expand M u);
    cbn [type_outer type_children members] in *; try discriminate;
    solve [exact C | apply Forall2_cons; [exact R | apply Forall2_nil]].
Qed.

Lemma expand_union : forall M t u xs, Solved M -> MergeEq M t u ->
  expand M t = TUnion xs ->
  exists ys, expand M u = TUnion ys /\ Forall2 (MergeEq M) xs ys.
Proof.
  intros M t u xs S E T. pose proof (expand_outer S E) as O.
  pose proof (expand_children S E) as C.
  rewrite T in O, C. destruct (expand M u); cbn [type_outer type_children] in O, C;
    try discriminate. eauto.
Qed.

Lemma forall2_member_left : forall A (R : A -> A -> Prop) xs ys,
  Forall2 R xs ys -> forall x, In x xs -> exists y, In y ys /\ R x y.
Proof.
  intros A R xs ys F. induction F as [|x y xs ys E F IH]; intros z I; [contradiction |].
  destruct I as [<-|I]; [exists y; auto using in_eq |].
  destruct (IH _ I) as [w [J Z]]. exists w. auto using in_cons.
Qed.

Lemma fitsM_transport : forall M t t' u u', Solved M ->
  MergeEq M t t' -> MergeEq M u u' -> FitsM M t u -> FitsM M t' u'.
Proof.
  intros M t t' u u' S T U [Same | [Never | [ms [Shape Member]]]].
  - left. now rewrite <- T, <- U.
  - right. left. now rewrite <- T.
  - right. right.
    destruct (expand_union S U Shape) as [ms' [Shape' C]].
    exists ms'. split; [exact Shape' | intros x' I].
    pose proof (expand_members S (MESym T)) as Ts.
    destruct (forall2_member_left Ts x' I) as [x [X ToX]].
    destruct (Member x X) as [y [Y ToY]].
    destruct (forall2_member_left C y Y) as [y' [Y' ToY']].
    exists y'. split; [exact Y' |].
    eapply METrans; [exact ToX | eapply METrans; eassumption].
Qed.

Global Instance fitsM_proper M (S : Solved M) :
  Proper (MergeEq M ==> MergeEq M ==> iff) (FitsM M).
Proof.
  intros t t' T u u' U. split; intro F.
  - eapply fitsM_transport; eassumption.
  - eapply fitsM_transport; [exact S | apply MESym; exact T | apply MESym; exact U | exact F].
Qed.

Global Instance headM_proper M (S : Solved M) : Proper (MergeEq M ==> iff) (HeadM M).
Proof.
  intros t u E. pose proof (expand_outer S E) as O. unfold HeadM.
  destruct (expand M t), (expand M u); cbn [type_outer head] in *;
    try discriminate; split; congruence.
Qed.

Theorem ilookM_first : forall A M (k stored : item) (a : A) l, Solved M ->
  ilookM M k l = Some (stored, a) <->
  exists pre post, l = pre ++ (stored, a) :: post /\
    Forall (fun q => ~ KeyEq M k (fst q)) pre /\ KeyEq M k stored.
Proof.
  intros A M k stored a l S. induction l as [|[j b] rest IH].
  - split; [discriminate | intros (pre & post & E & _); destruct pre; discriminate].
  - cbn [ilookM]. destruct (item_eqbM M k j) eqn:B.
    + apply (item_eqbM_spec S) in B. split.
      * intro E. injection E as <- <-. exists [], rest. cbn. auto.
      * intros (pre & post & E & Before & Match). destruct pre as [|[j' b'] pre].
        -- cbn in E. congruence.
        -- cbn in E. injection E as <- <- _. inversion Before. contradiction.
    + assert (NoMatch : ~ KeyEq M k j).
      { intro E. apply (item_eqbM_spec S) in E. congruence. }
      rewrite IH. split.
      * intros (pre & post & -> & Before & Match).
        exists ((j,b) :: pre), post. cbn. repeat split; auto.
      * intros (pre & post & E & Before & Match). destruct pre as [|[j' b'] pre].
        -- cbn in E. injection E as -> -> _. contradiction.
        -- cbn in E. injection E as <- <- ->. inversion Before; subst.
           exists pre, post. auto.
Qed.

Theorem joinM_deterministic : forall M a b expected t u,
  JoinM M a b expected t -> JoinM M a b expected u -> t = u.
Proof.
  intros M a b expected t u T U. inversion T; subst; inversion U; subst;
    try reflexivity; contradiction.
Qed.

Lemma table_read_agrees : forall M s tm tm', SectionOf M s -> InstEq M tm tm' ->
  PublicTypeRead.Agree s s tm tm'.
Proof.
  intros M s tm tm' Section Tables.
  assert (Rows : Forall2 (PublicTypeRead.Rel s s) tm tm').
  { induction Tables as [|a b l l' [Keys Types] _ IH]; constructor; [|exact IH].
    split; [exact Keys |]. apply (merge_section_kernel Section). exact Types. }
  exact (proj2 (PublicTypeRead.rel_nlook s s tm tm' Rows 0)).
Qed.

Lemma optional_read_agrees : forall M s a b, SectionOf M s ->
  OptionEq (MergeEq M) a b -> forall t u, a = Some t -> b = Some u ->
  app_subst s t = app_subst s u.
Proof.
  intros M s a b Section E t u -> ->.
  apply (merge_section_kernel Section). exact E.
Qed.

(* Transport of derivability requires the union rule to inspect expanded
   members. These lemmas compare the types when both readings exist. *)
Theorem tyof_merge_agree : forall M W p tm tm' this this' a t u,
  Solved M -> InstEq M tm tm' -> OptionEq (MergeEq M) this this' ->
  TyOf W p tm this a t -> TyOf W p tm' this' a u -> MergeEq M t u.
Proof.
  intros M W p tm tm' this this' a t u S Tables Receivers L R.
  destruct (solved_has_section S) as [s Section].
  apply (merge_section_kernel Section).
  eapply PublicTypeRead.tyof_rel; [exact L | exact R | |].
  - eapply table_read_agrees; eassumption.
  - eapply optional_read_agrees; eassumption.
Qed.

Theorem sigof_merge_agree : forall M W f tm tm' this this' g h,
  Solved M -> InstEq M tm tm' -> OptionEq (MergeEq M) this this' ->
  SigOf W f tm this g -> SigOf W f tm' this' h -> SigEq M g h.
Proof.
  intros M W f tm tm' this this' g h S Tables Receivers L R.
  destruct (solved_has_section S) as [s Section].
  apply (section_sig_eq Section).
  pose proof (@table_read_agrees M s tm tm' Section Tables) as Agree.
  pose proof (@optional_read_agrees M s this this' Section Receivers) as This.
  destruct (PublicTypeRead.sig_rel W s s f tm tm' this this' g h L R Agree This) as [P T].
  destruct g, h. unfold sig_subst. cbn in P, T |- *. now rewrite P, T.
Qed.
