Global Instance merge_eq_equivalence M : Equivalence (MergeEq M).
Proof.
  split.
  - exact (@MERefl M).
  - exact (@MESym M).
  - exact (@METrans M).
Qed.

(* Composition acts through the same template as MECong. *)
Definition compose (outer inner : subst) : subst :=
  map (fun q => (fst q, app_subst outer (snd q))) inner ++ outer.

Lemma compose_abs : forall outer inner x,
  app_subst (compose outer inner) (TAbs x) =
  app_subst outer (app_subst inner (TAbs x)).
Proof.
  intros outer inner. induction inner as [|[y t] inner IH]; intro x.
  - reflexivity.
  - cbn [compose map app app_subst lookup_subst fst snd].
    destruct (Nat.eqb x y); [reflexivity | apply IH].
Qed.

Lemma compose_read : forall outer inner t,
  app_subst (compose outer inner) t = app_subst outer (app_subst inner t).
Proof.
  intros outer inner t.
  rewrite <- (PublicTypeRead.app_subst_nil t) at 1.
  apply PublicTypeRead.subst2_agree. intros x _. apply compose_abs.
Qed.

Theorem merge_eq_substitute : forall M N s,
  Respects M s N -> forall t u, MergeEq M t u ->
    MergeEq N (app_subst s t) (app_subst s u).
Proof.
  intros M N s [Members Shapes] t u H. induction H.
  - apply MERefl.
  - apply MESym. assumption.
  - eapply METrans; eassumption.
  - eapply Members; eassumption.
  - eapply Shapes; eassumption.
  - rewrite <- !compose_read. apply MECong.
    intros x InX. rewrite !compose_abs. auto.
Qed.

Definition SolvesClasses (M : merge) (s : subst) : Prop :=
  (forall c x y, In c M -> In x (mc_members c) -> In y (mc_members c) ->
     app_subst s (TAbs x) = app_subst s (TAbs y)) /\
  (forall c x t, In c M -> In x (mc_members c) -> mc_shape c = Some t ->
     app_subst s (TAbs x) = app_subst s t).

Theorem merge_eq_sound : forall M s,
  SolvesClasses M s -> forall t u, MergeEq M t u -> app_subst s t = app_subst s u.
Proof.
  intros M s [Members Shapes] t u H. induction H.
  - reflexivity.
  - symmetry. assumption.
  - etransitivity; eassumption.
  - eapply Members; eassumption.
  - eapply Shapes; eassumption.
  - apply PublicTypeRead.subst2_agree. auto.
Qed.

Lemma merge_eq_read : forall M s,
  (forall x, MergeEq M (TAbs x) (app_subst s (TAbs x))) ->
  forall t, MergeEq M t (app_subst s t).
Proof.
  intros M s Reads t. rewrite <- (PublicTypeRead.app_subst_nil t) at 1.
  apply MECong. intros x _. apply Reads.
Qed.

Theorem merge_section_kernel : forall M s, SectionOf M s ->
  forall t u, MergeEq M t u <-> app_subst s t = app_subst s u.
Proof.
  intros M s [Read Constant] t u. split; [apply Constant |].
  intros Equal. eapply METrans; [apply merge_eq_read; exact Read |].
  rewrite Equal. apply MESym, merge_eq_read. exact Read.
Qed.

(* A substitution respects a presentation when it respects the equations
   of any one of its sections. *)
Theorem respects_section : forall M N s section,
  SectionOf M section ->
  (forall x t, In (x, t) section ->
    MergeEq N (app_subst s (TAbs x)) (app_subst s t)) ->
  Respects M s N.
Proof.
  intros M N s section Section Rows.
  assert (Read : forall t, MergeEq N (app_subst s t) (app_subst s (app_subst section t))).
  { intro t. rewrite <- compose_read. apply MECong. intros x _.
    rewrite compose_abs.
    change (MergeEq N (app_subst s (TAbs x))
      (app_subst s (match lookup_subst x section with Some u => u | None => TAbs x end))).
    destruct (lookup_subst x section) as [u |] eqn:L; [|apply MERefl].
    apply Rows, PublicOrientation.lookup_subst_pair. exact L. }
  assert (Respect : forall t u, MergeEq M t u -> MergeEq N (app_subst s t) (app_subst s u)).
  { intros t u Equal. apply (merge_section_kernel Section) in Equal.
    eapply METrans; [apply Read |]. rewrite Equal. apply MESym, Read. }
  split.
  - intros c x y C X Y. apply Respect. eapply MEClass; eassumption.
  - intros c x t C X Shape. apply Respect. eapply MEShape; eassumption.
Qed.

Lemma mapped_list_eq : forall A B (f : A -> B) xs ys,
  Forall2 (fun x y => f x = f y) xs ys <-> map f xs = map f ys.
Proof.
  intros A B f xs ys. split.
  - intro H. induction H; cbn; [reflexivity | congruence].
  - revert ys. induction xs as [|x xs IH]; intros [|y ys] Eq;
      cbn in Eq; try discriminate; constructor.
    + congruence.
    + apply IH. congruence.
Qed.

Lemma section_key_eq : forall M s, SectionOf M s ->
  forall k k', KeyEq M k k' <->
    app_subst_item s (provision_id k) = app_subst_item s (provision_id k').
Proof.
  intros M s Section k k'.
  destruct k; destruct k'; cbn [KeyEq provision_id app_subst_item map_snd];
    try (split; congruence).
  rewrite (merge_section_kernel Section). split.
  - intros [-> ->]. reflexivity.
  - intro E. injection E. auto.
Qed.

Lemma section_sig_eq : forall M s, SectionOf M s ->
  forall g g', SigEq M g g' <-> sig_subst s g = sig_subst s g'.
Proof.
  intros M s Section [ps t] [ps' t']. unfold SigEq, sig_subst. cbn.
  rewrite (merge_section_kernel Section).
  assert (Params : Forall2 (MergeEq M) ps ps' <->
                   map (app_subst s) ps = map (app_subst s) ps').
  { rewrite <- mapped_list_eq. split; intro F; induction F;
      constructor; try assumption; apply (merge_section_kernel Section); assumption. }
  rewrite Params. split.
  - intros [-> ->]. reflexivity.
  - intro E. injection E. auto.
Qed.

Lemma section_inst_eq : forall M s, SectionOf M s ->
  forall a b, InstEq M a b <->
    map (fun q => (fst q, app_subst s (snd q))) a =
    map (fun q => (fst q, app_subst s (snd q))) b.
Proof.
  intros M s Section a b. unfold InstEq. rewrite <- mapped_list_eq.
  split; intro F; induction F; constructor; try assumption.
  - destruct H as [Keys Values]. cbn. rewrite Keys, (proj1 (merge_section_kernel Section _ _) Values).
    reflexivity.
  - cbn in H. injection H as Keys Values. split; [exact Keys |].
    apply (merge_section_kernel Section). exact Values.
Qed.

Lemma option_eq_map : forall A B (R : A -> A -> Prop) (f : A -> B),
  (forall x y, R x y <-> f x = f y) ->
  forall a b, OptionEq R a b <-> option_map f a = option_map f b.
Proof.
  intros A B R f Equiv [a|] [b|]; cbn [OptionEq option_map].
  - rewrite Equiv. split; congruence.
  - split; [contradiction | discriminate].
  - split; [contradiction | discriminate].
  - split; auto.
Qed.

Lemma entry_key_raw : forall s e,
  entry_key s e = option_map (app_subst_item s) (raw_entry_key e).
Proof. intros s []; reflexivity. Qed.

Lemma entry_sig_raw : forall s e,
  entry_sig s e = option_map (sig_subst s) (raw_entry_sig e).
Proof. intros s []; reflexivity. Qed.

Lemma entry_inst_raw : forall s e,
  entry_inst s e = option_map (map (fun q => (fst q, app_subst s (snd q)))) (raw_entry_inst e).
Proof.
  intros s []; unfold entry_inst, raw_entry_inst, inst_read, read_inst; cbn;
    try reflexivity; rewrite map_map; reflexivity.
Qed.

Lemma raw_key_identity : forall e k, raw_entry_key e = Some k -> provision_id k = k.
Proof. intros [] k E; cbn in E; try discriminate; injection E as <-; reflexivity. Qed.

Theorem section_unifies : forall M s es, SectionOf M s ->
  (UnifiesMerge M es <-> Unifies s es).
Proof.
  intros M s es Section. unfold UnifiesMerge, Unifies.
  split; intros [Pairs Equations]; split.
  - intros e e' k InE InE' K K'. rewrite entry_key_raw in K, K'.
    destruct (raw_entry_key e) as [r|] eqn:R; [|discriminate].
    destruct (raw_entry_key e') as [r'|] eqn:R'; [|discriminate].
    injection K as <-. injection K' as Equal.
    assert (Keys : KeyEq M r r').
    { apply (section_key_eq Section). rewrite (raw_key_identity _ R), (raw_key_identity _ R').
      symmetry. exact Equal. }
    destruct (Pairs e e' r r' InE InE' R R' Keys) as [Sigs Insts].
    split.
    + rewrite !entry_sig_raw. apply option_eq_map with (R := SigEq M);
        [apply section_sig_eq; assumption | exact Sigs].
    + rewrite !entry_inst_raw. apply option_eq_map with (R := InstEq M);
        [apply section_inst_eq; assumption | exact Insts].
  - intros l r I. apply (merge_section_kernel Section). apply Equations. exact I.
  - intros e e' r r' InE InE' R R' Keys.
    apply (section_key_eq Section) in Keys.
    rewrite (raw_key_identity _ R), (raw_key_identity _ R') in Keys.
    assert (K : entry_key s e = Some (app_subst_item s r)) by (rewrite entry_key_raw, R; reflexivity).
    assert (K' : entry_key s e' = Some (app_subst_item s r)) by (rewrite entry_key_raw, R', Keys; reflexivity).
    destruct (Pairs e e' _ InE InE' K K') as [Sigs Insts].
    split.
    + apply option_eq_map with (f := sig_subst s);
        [apply section_sig_eq; assumption | rewrite <- !entry_sig_raw; exact Sigs].
    + apply option_eq_map with (f := map (fun q => (fst q, app_subst s (snd q))));
        [apply section_inst_eq; assumption | rewrite <- !entry_inst_raw; exact Insts].
  - intros l r I. apply (merge_section_kernel Section). apply Equations. exact I.
Qed.

(* Principality gives the forward implication directly. Any section is a
   separating unifier, which supplies the reverse implication. *)
Theorem merge_semantic_reading_with_section : forall es M s,
  MergeOf es M -> SectionOf M s ->
  forall t u, MergeEq M t u <-> forall r, Unifies r es -> app_subst r t = app_subst r u.
Proof.
  intros es M s [_ [_ [_ [UnifiesM Principal]]]] Section t u. split.
  - intros E r U. exact (Principal r U t u E).
  - intro All. apply (merge_section_kernel Section). apply All.
    apply (section_unifies es Section). exact UnifiesM.
Qed.

Theorem section_is_most_general : forall es M s,
  MergeOf es M -> SectionOf M s ->
  (forall g t, In (g, t) s -> In g (flat_map entry_gens es) /\ incl (gens t) (flat_map entry_gens es)) ->
  (forall g t, In (g, t) s -> lookup_subst g s = Some t) ->
  MostGeneralMerge s es.
Proof.
  intros es M s [_ [_ [_ [UnifiesM Principal]]]] [Read Constant] Support Functional.
  assert (Section : SectionOf M s) by (split; assumption).
  split; [apply (section_unifies es Section); exact UnifiesM |].
  split.
  - intro t. symmetry. apply Constant, merge_eq_read. exact Read.
  - split; [|split; assumption]. intros r U t. symmetry. apply Principal.
    + exact U.
    + apply merge_eq_read. exact Read.
Qed.

(* A class's members have the same rank, so any member can be used to
   count the classes strictly below it in a proof. *)
Definition class_rank (rank : tsym -> nat) (c : mclass) : nat :=
  match mc_members c with [] => 0 | x :: _ => rank x end.

Lemma class_rank_member : forall (rank : tsym -> nat) (M : merge),
  (forall c x y, In c M -> In x (mc_members c) -> In y (mc_members c) -> rank x = rank y) ->
  forall c x, In c M -> In x (mc_members c) -> class_rank rank c = rank x.
Proof.
  intros rank M Same c x InC InX. unfold class_rank.
  destruct (mc_members c) as [|y rest] eqn:Members; [contradiction |].
  apply (Same c y x InC); rewrite Members; [left; reflexivity | exact InX].
Qed.

Lemma filter_le : forall A (p q : A -> bool) xs,
  (forall x, In x xs -> p x = true -> q x = true) ->
  length (filter p xs) <= length (filter q xs).
Proof.
  intros A p q xs. induction xs as [|x xs IH]; intro Imp; cbn; [lia |].
  specialize (IH ltac:(intros z I H; apply Imp; [right; exact I | exact H])).
  destruct (p x) eqn:P, (q x) eqn:Q; cbn; try lia.
  specialize (Imp x (or_introl eq_refl) P). congruence.
Qed.

Lemma filter_lt : forall A (p q : A -> bool) xs,
  (forall x, In x xs -> p x = true -> q x = true) ->
  (exists x, In x xs /\ p x = false /\ q x = true) ->
  length (filter p xs) < length (filter q xs).
Proof.
  intros A p q xs. induction xs as [|x xs IH]; intros Imp [y [InY [Py Qy]]]; [contradiction |].
  assert (Rest : forall z, In z xs -> p z = true -> q z = true).
  { intros z I H. apply Imp; [right; exact I | exact H]. }
  destruct InY as [<- | InY].
  - cbn. rewrite Py, Qy. cbn. pose proof (filter_le p q xs Rest). lia.
  - specialize (IH Rest ltac:(exists y; tauto)).
    cbn. destruct (p x) eqn:P, (q x) eqn:Q; cbn; try lia.
    specialize (Imp x (or_introl eq_refl) P). congruence.
Qed.

Definition BelowRank (M : merge) (level : tsym -> nat) : Prop :=
  (forall c x, In c M -> In x (mc_members c) -> level x < length M) /\
  (forall c t x y d, In c M -> mc_shape c = Some t ->
    In x (mc_members c) -> In y (gens t) -> In d M -> In y (mc_members d) -> level y < level x).

Lemma bounded_rank : forall M, Solved M -> exists level, BelowRank M level.
Proof.
  intros M [_ [_ [rank [Same Descend]]]].
  exists (fun x => length (filter (fun c => Nat.ltb (class_rank rank c) (rank x)) M)).
  split.
  - intros c x InC InX.
    assert (N : length (filter (fun d => true) M) = length M) by
      (clear - M; induction M; cbn; congruence).
    rewrite <- N.
    apply filter_lt.
    + auto.
    + exists c. split; [exact InC |]. split; [|reflexivity].
      rewrite (@class_rank_member rank M Same c x InC InX), Nat.ltb_irrefl. reflexivity.
  - intros c t x y d InC Shape InX InY InD MemberY.
    pose proof (Descend _ _ _ _ InC Shape InX InY) as LT.
    apply filter_lt.
    + intros z InZ H. apply Nat.ltb_lt in H. apply Nat.ltb_lt. lia.
    + exists d. split; [exact InD |].
      rewrite (@class_rank_member rank M Same d y InD MemberY), Nat.ltb_irrefl.
      split; [reflexivity | apply Nat.ltb_lt; exact LT].
Qed.

Lemma nodup_app_disjoint : forall A (xs ys : list A) x,
  NoDup (xs ++ ys) -> In x xs -> ~ In x ys.
Proof.
  intros A xs. induction xs as [|y xs IH]; intros ys x ND InX InY; [contradiction |].
  inversion ND as [|? ? NotIn Tail]; subst.
  destruct InX as [<- | InX].
  - apply NotIn. apply in_or_app. right. exact InY.
  - eapply IH; eassumption.
Qed.

Lemma distinct_class_member : forall M c x,
  NoDup (flat_map mc_members M) -> In c M -> In x (mc_members c) ->
  forall d, In d M -> In x (mc_members d) -> c = d.
Proof.
  induction M as [|h rest IH]; intros c x Unique InC InX d InD InXD; [contradiction |].
  cbn in Unique. destruct InC as [<-|InC], InD as [<-|InD]; [reflexivity | | |].
  - exfalso. eapply nodup_app_disjoint; [exact Unique | exact InX |].
    apply in_flat_map. exists d. tauto.
  - exfalso. eapply nodup_app_disjoint; [exact Unique | exact InXD |].
    apply in_flat_map. exists c. tauto.
  - eapply IH; [apply (NoDup_app_remove_l _ _ Unique) | exact InC | exact InX | exact InD | exact InXD].
Qed.

Lemma shape_pair : forall M n x v, In (x, v) (shape_table M (S n)) <->
  exists c t, In c M /\ In x (mc_members c) /\ mc_shape c = Some t /\
    v = app_subst (shape_table M n) t.
Proof.
  intros M n x v. cbn [shape_table]. rewrite in_flat_map. split.
  - intros [c [InC Pair]].
    destruct (mc_shape c) as [t|] eqn:Shape; [|contradiction].
    apply in_map_iff in Pair. destruct Pair as [y [E InY]].
    injection E as <- <-. exists c, t. tauto.
  - intros (c & t & InC & InX & Shape & ->). exists c. split; [exact InC |].
    rewrite Shape. apply in_map_iff. exists x. tauto.
Qed.

Lemma lookup_subst_function : forall s x v,
  In (x, v) s ->
  (forall w, In (x, w) s -> w = v) ->
  lookup_subst x s = Some v.
Proof.
  induction s as [|[y t] s IH]; intros x v InX One; [contradiction |].
  cbn. destruct (Nat.eqb x y) eqn:Eq.
  - apply Nat.eqb_eq in Eq. subst y. rewrite (One t (or_introl eq_refl)). reflexivity.
  - apply IH.
    + destruct InX as [E|E]; [injection E as <- <-; rewrite Nat.eqb_refl in Eq; discriminate | exact E].
    + intros w I. apply One. right. exact I.
Qed.

Lemma shape_lookup_at : forall M n c x t,
  NoDup (flat_map mc_members M) -> In c M -> In x (mc_members c) ->
  mc_shape c = Some t ->
  lookup_subst x (shape_table M (S n)) = Some (app_subst (shape_table M n) t).
Proof.
  intros M n c x t ND InC InX Shape. apply lookup_subst_function.
  - apply shape_pair. exists c, t. tauto.
  - intros w W. apply shape_pair in W. destruct W as (d & u & InD & InXD & ShapeD & ->).
    assert (c = d) by (eapply distinct_class_member; eassumption).
    subst d. congruence.
Qed.

Lemma shape_lookup_none : forall M n x,
  (forall c, In c M -> In x (mc_members c) -> mc_shape c = None) ->
  lookup_subst x (shape_table M n) = None.
Proof.
  intros M [|n] x NoShape; [reflexivity |].
  destruct (lookup_subst x (shape_table M (S n))) as [t|] eqn:L; [|reflexivity].
  apply PublicOrientation.lookup_subst_pair, shape_pair in L.
  destruct L as (c & u & InC & InX & Shape & _). specialize (NoShape c InC InX). congruence.
Qed.

Definition RankWithin (M : merge) (level : tsym -> nat) (n : nat) (t : ty) : Prop :=
  forall x c, In x (gens t) -> In c M -> In x (mc_members c) ->
    mc_shape c <> None -> level x < n.

Lemma shape_below : forall M level n c x t,
  BelowRank M level -> In c M -> In x (mc_members c) -> mc_shape c = Some t ->
  level x < S n -> RankWithin M level n t.
Proof.
  intros M level n c x t [_ Descend] InC InX Shape LT y d InY InD MemberY _.
  pose proof (Descend c t x y d InC Shape InX InY InD MemberY). lia.
Qed.

Lemma shape_stable : forall M level,
  NoDup (flat_map mc_members M) -> BelowRank M level ->
  forall n m t, n <= m -> RankWithin M level n t ->
  app_subst (shape_table M n) t = app_subst (shape_table M m) t.
Proof.
  intros M level ND Ranks. induction n as [|n IH]; intros m t LE Within.
  - apply PublicTypeRead.subst_agree_on. intros x InX. cbn [app_subst shape_table lookup_subst].
    rewrite shape_lookup_none; [reflexivity |].
    intros c InC MemberX. destruct (mc_shape c) eqn:Shape; [|reflexivity].
    specialize (Within x c InX InC MemberX ltac:(congruence)). lia.
  - destruct m as [|m]; [lia |].
    apply PublicTypeRead.subst_agree_on. intros x InX. cbn [app_subst].
    destruct (lookup_subst x (shape_table M (S n))) as [v|] eqn:L.
    + apply PublicOrientation.lookup_subst_pair, shape_pair in L.
      destruct L as (c & u & InC & MemberX & Shape & ->).
      rewrite (@shape_lookup_at M m c x u ND InC MemberX Shape).
      apply IH; [lia |]. eapply shape_below; try eassumption.
      apply (Within x c InX InC MemberX). congruence.
    + destruct (lookup_subst x (shape_table M (S m))) as [v|] eqn:L'; [|reflexivity].
      apply PublicOrientation.lookup_subst_pair, shape_pair in L'.
      destruct L' as (c & u & InC & MemberX & Shape & ->).
      rewrite (@shape_lookup_at M n c x u ND InC MemberX Shape) in L. discriminate.
Qed.

Lemma expand_member_shape : forall M c x t,
  Solved M -> In c M -> In x (mc_members c) -> mc_shape c = Some t ->
  expand M (TAbs x) = expand M t.
Proof.
  intros M c x t SolvedM InC InX Shape.
  destruct (bounded_rank SolvedM) as [level Ranks].
  pose proof (proj1 SolvedM) as ND.
  unfold expand.
  destruct (length M) as [|n] eqn:Size.
  { apply length_zero_iff_nil in Size. subst M. contradiction. }
  cbn [app_subst]. rewrite (@shape_lookup_at M n c x t ND InC InX Shape).
  eapply shape_stable; [exact ND | exact Ranks | lia |].
  eapply shape_below; try eassumption.
  rewrite <- Size. exact (proj1 Ranks c x InC InX).
Qed.

Theorem expand_mergeeq : forall M t, MergeEq M t (expand M t).
Proof.
  intros M t. unfold expand. generalize (length M). intro n. revert t.
  induction n as [|n IH]; intro t.
  - cbn [shape_table]. rewrite PublicTypeRead.app_subst_nil. apply MERefl.
  - apply merge_eq_read. intro x. cbn [app_subst].
    destruct (lookup_subst x (shape_table M (S n))) as [v|] eqn:L; [|apply MERefl].
    apply PublicOrientation.lookup_subst_pair, shape_pair in L.
    destruct L as (c & u & InC & InX & Shape & ->).
    eapply METrans; [eapply MEShape; eassumption | apply IH].
Qed.

(* This table is a proof device. The public operations leave the spelling
   of variables in symbol-only classes intact. *)
Local Definition symbol_table (M : merge) : subst :=
  flat_map (fun c => match mc_members c with
    | [] => []
    | h :: _ => map (fun x => (x, TAbs h)) (mc_members c)
    end) M.

Lemma symbol_pair : forall M x t, In (x, t) (symbol_table M) <->
  exists c h rest, In c M /\ mc_members c = h :: rest /\
    In x (mc_members c) /\ t = TAbs h.
Proof.
  intros M x t. unfold symbol_table. rewrite in_flat_map. split.
  - intros [c [InC I]]. destruct (mc_members c) as [|h rest] eqn:Members;
      [contradiction |].
    apply in_map_iff in I. destruct I as [y [E InY]]. injection E as <- <-.
    exists c, h, rest. repeat split; try assumption. rewrite Members. exact InY.
  - intros (c & h & rest & InC & Members & InX & ->).
    exists c. split; [exact InC |].
    rewrite Members. apply in_map_iff. exists x. split; [reflexivity |].
    rewrite <- Members. exact InX.
Qed.

Lemma symbol_lookup_at : forall M c h rest x,
  NoDup (flat_map mc_members M) -> In c M -> mc_members c = h :: rest ->
  In x (mc_members c) -> lookup_subst x (symbol_table M) = Some (TAbs h).
Proof.
  intros M c h rest x ND InC Members InX. apply lookup_subst_function.
  - apply symbol_pair. exists c, h, rest. tauto.
  - intros w I. apply symbol_pair in I. destruct I as (d & k & tail & InD & Other & InXD & ->).
    assert (c = d) by (eapply distinct_class_member; eassumption).
    subst d. congruence.
Qed.

Lemma symbol_read : forall M t, MergeEq M t (app_subst (symbol_table M) t).
Proof.
  intros M. apply merge_eq_read. intros x. cbn [app_subst].
  destruct (lookup_subst x (symbol_table M)) as [v|] eqn:L; [|apply MERefl].
  apply PublicOrientation.lookup_subst_pair, symbol_pair in L.
  destruct L as (c & h & rest & InC & Members & InX & ->).
  eapply MEClass; [exact InC | exact InX |]. rewrite Members. left. reflexivity.
Qed.

Local Definition section_table (M : merge) : subst :=
  map (fun p => (fst p, app_subst (symbol_table M) (expand M (TAbs (fst p)))))
    (symbol_table M).

Lemma lookup_map_domain : forall f s x,
  lookup_subst x (map (fun p => (fst p, f (fst p))) s) =
  match lookup_subst x s with Some _ => Some (f x) | None => None end.
Proof.
  intros f s. induction s as [|[y t] s IH]; intros x; [reflexivity |].
  cbn [lookup_subst map fst]. destruct (Nat.eqb x y) eqn:E; [|apply IH].
  apply Nat.eqb_eq in E. now subst y.
Qed.

Lemma section_table_read : forall M t,
  app_subst (section_table M) t = app_subst (symbol_table M) (expand M t).
Proof.
  intros M t. unfold expand. rewrite <- compose_read.
  apply PublicTypeRead.subst_agree_on. intros x _. rewrite compose_abs.
  unfold section_table. cbn [app_subst]. rewrite (@lookup_map_domain (fun y => app_subst (symbol_table M) (expand M (TAbs y))) _ x).
  destruct (lookup_subst x (symbol_table M)) as [h|] eqn:L; [reflexivity |].
  assert (N : lookup_subst x (shape_table M (length M)) = None).
  { destruct (length M) as [|n]; [reflexivity |].
    destruct (lookup_subst x (shape_table M (S n))) as [v|] eqn:E; [|reflexivity].
    apply PublicOrientation.lookup_subst_pair, shape_pair in E.
    destruct E as (c & u & C & X & Sh & _).
    destruct (mc_members c) as [|y rest] eqn:Members; [contradiction |].
    assert (I : In (x, TAbs y) (symbol_table M)).
    { apply symbol_pair. exists c,y,rest. repeat split; try assumption.
      rewrite Members. exact X. }
    assert (J : In x (map fst (symbol_table M))).
    { apply in_map_iff. exists (x,TAbs y). auto. }
    exfalso. exact (PublicCallRealize.lookup_subst_in x _ J L). }
  rewrite N. cbn [app_subst]. now rewrite L.
Qed.

Lemma expand_unshaped : forall M c x,
  NoDup (flat_map mc_members M) -> In c M -> In x (mc_members c) ->
  mc_shape c = None -> expand M (TAbs x) = TAbs x.
Proof.
  intros M c x ND InC InX Shape. unfold expand. cbn [app_subst].
  rewrite shape_lookup_none; [reflexivity |].
  intros d InD InXD. assert (c = d) by (eapply distinct_class_member; eassumption).
  congruence.
Qed.

Lemma section_table_is_section : forall M, Solved M -> SectionOf M (section_table M).
Proof.
  intros M S. pose proof (proj1 S) as ND. split.
  - intros x. rewrite section_table_read.
    eapply METrans; [apply expand_mergeeq | apply symbol_read].
  - apply merge_eq_sound. split.
    + intros c x y InC InX InY. rewrite !section_table_read.
      destruct (mc_shape c) as [t|] eqn:Shape.
      * rewrite (@expand_member_shape M c x t S InC InX Shape).
        rewrite (@expand_member_shape M c y t S InC InY Shape). reflexivity.
      * rewrite (@expand_unshaped M c x ND InC InX Shape).
        rewrite (@expand_unshaped M c y ND InC InY Shape).
        destruct (mc_members c) as [|h rest] eqn:Members; [contradiction |].
        assert (InX' : In x (mc_members c)) by (rewrite Members; exact InX).
        assert (InY' : In y (mc_members c)) by (rewrite Members; exact InY).
        cbn [app_subst].
        rewrite (@symbol_lookup_at M c h rest x ND InC Members InX').
        rewrite (@symbol_lookup_at M c h rest y ND InC Members InY'). reflexivity.
    + intros c x t InC InX Shape. rewrite !section_table_read.
      rewrite (@expand_member_shape M c x t S InC InX Shape). reflexivity.
Qed.

Theorem solved_has_section : forall M, Solved M -> exists s, SectionOf M s.
Proof. intros M S. exists (section_table M). apply section_table_is_section. exact S. Qed.

Theorem merge_semantic_reading : forall es M,
  MergeOf es M -> forall t u, MergeEq M t u <->
    forall r, Unifies r es -> app_subst r t = app_subst r u.
Proof.
  intros es M Merges. destruct (solved_has_section (proj1 Merges)) as [s Section].
  eapply merge_semantic_reading_with_section; eassumption.
Qed.

Theorem merge_presentation_independent : forall es M N,
  MergeOf es M -> MergeOf es N -> forall t u, MergeEq M t u <-> MergeEq N t u.
Proof.
  intros es M N MergeM MergeN t u.
  rewrite (merge_semantic_reading MergeM), (merge_semantic_reading MergeN). reflexivity.
Qed.

Lemma same_classb_spec : forall M x y,
  same_classb M x y = true <->
  x = y \/ exists c, In c M /\ In x (mc_members c) /\ In y (mc_members c).
Proof.
  intros M x y. unfold same_classb. rewrite orb_true_iff, Nat.eqb_eq, existsb_exists.
  assert (Member : forall z zs, existsb (Nat.eqb z) zs = true <-> In z zs).
  { intros z zs. rewrite existsb_exists. split.
    - intros [w [I Eq]]. apply Nat.eqb_eq in Eq. now subst w.
    - intro I. exists z. rewrite Nat.eqb_refl. auto. }
  split; intros [Eq | [c [InC Same]]]; try (left; exact Eq);
    right; exists c; split; [exact InC | | exact InC |].
  - now rewrite andb_true_iff, !Member in Same.
  - now rewrite andb_true_iff, !Member.
Qed.

Local Definition symbol_at (M : merge) (x : tsym) : tsym :=
  match lookup_subst x (symbol_table M) with Some (TAbs h) => h | _ => x end.

Lemma symbol_at_read : forall M x,
  app_subst (symbol_table M) (TAbs x) = TAbs (symbol_at M x).
Proof.
  intros M x. unfold symbol_at. cbn [app_subst].
  destruct (lookup_subst x (symbol_table M)) as [v|] eqn:L; [|reflexivity].
  apply PublicOrientation.lookup_subst_pair, symbol_pair in L.
  destruct L as (c & h & rest & InC & Members & InX & ->). reflexivity.
Qed.

Lemma symbol_at_member : forall M c h rest x,
  NoDup (flat_map mc_members M) -> In c M -> mc_members c = h :: rest ->
  In x (mc_members c) -> symbol_at M x = h.
Proof.
  intros M c h rest x ND InC Members InX. unfold symbol_at.
  rewrite (@symbol_lookup_at M c h rest x ND InC Members InX). reflexivity.
Qed.

Lemma same_classb_read : forall M x y,
  NoDup (flat_map mc_members M) ->
  (same_classb M x y = true <-> symbol_at M x = symbol_at M y).
Proof.
  intros M x y ND. rewrite same_classb_spec. split.
  - intros [-> | (c & InC & InX & InY)]; [reflexivity |].
    destruct (mc_members c) as [|h rest] eqn:Members; [contradiction |].
    assert (InX' : In x (mc_members c)) by (rewrite Members; exact InX).
    assert (InY' : In y (mc_members c)) by (rewrite Members; exact InY).
    rewrite (@symbol_at_member M c h rest x ND InC Members InX').
    rewrite (@symbol_at_member M c h rest y ND InC Members InY'). reflexivity.
  - unfold symbol_at.
    destruct (lookup_subst x (symbol_table M)) as [v|] eqn:L,
      (lookup_subst y (symbol_table M)) as [w|] eqn:R.
    + apply PublicOrientation.lookup_subst_pair, symbol_pair in L, R.
      destruct L as (c & h & rest & InC & Members & InX & ->).
      destruct R as (d & j & tail & InD & Other & InY & ->). intros <-.
      assert (E : c = d).
      { eapply distinct_class_member with (x := h); try eassumption;
          rewrite ?Members, ?Other; left; reflexivity. }
      subst d. right. exists c. tauto.
    + apply PublicOrientation.lookup_subst_pair, symbol_pair in L.
      destruct L as (c & h & rest & InC & Members & InX & ->). intros <-.
      assert (InH : In h (mc_members c)) by (rewrite Members; left; reflexivity).
      rewrite (@symbol_lookup_at M c h rest h ND InC Members InH) in R. discriminate.
    + apply PublicOrientation.lookup_subst_pair, symbol_pair in R.
      destruct R as (c & h & rest & InC & Members & InY & ->). intros ->.
      assert (InH : In h (mc_members c)) by (rewrite Members; left; reflexivity).
      rewrite (@symbol_lookup_at M c h rest h ND InC Members InH) in L. discriminate.
    + auto.
Qed.

Lemma merge_ty_eqb_read : forall M,
  NoDup (flat_map mc_members M) -> forall t u,
    ty_eqb_with (same_classb M) t u = true <->
    app_subst (symbol_table M) t = app_subst (symbol_table M) u.
Proof.
  intros M ND. fix IH 1.
  intros [m|fs| |x|n args|ms] [m'|gs| |y|n' args'|ns];
    rewrite ?symbol_at_read, ?PublicTypeRead.subst_record, ?PublicTypeRead.subst_nom,
      ?PublicTypeRead.subst_union;
    cbn [ty_eqb_with app_subst]; try (split; congruence).
  - rewrite Nat.eqb_eq. split; congruence.
  - assert (Rows : forall gs,
        (fix go (fs gs : list (string * ty)) :=
           match fs, gs with
           | [], [] => true
           | (f,t)::fs, (g,u)::gs =>
               String.eqb f g && ty_eqb_with (same_classb M) t u && go fs gs
           | _, _ => false end) fs gs = true <->
        map (fun q => (fst q, app_subst (symbol_table M) (snd q))) fs =
        map (fun q => (fst q, app_subst (symbol_table M) (snd q))) gs).
    { induction fs as [|[f t] fs Tail]; intros [|[g u] rest];
        cbn; try (split; congruence).
      rewrite !andb_true_iff, String.eqb_eq, IH, Tail.
      split; [intros [[-> ->] ->]; reflexivity | intro E; injection E; auto]. }
    rewrite Rows. split; congruence.
  - rewrite (@same_classb_read M x y ND). split; congruence.
  - assert (Rows : forall args',
        (fix go (xs ys : list (tsym * ty)) :=
           match xs, ys with
           | [], [] => true
           | p :: rest, q :: tail =>
               Nat.eqb (fst p) (fst q) &&
               ty_eqb_with (same_classb M) (snd p) (snd q) && go rest tail
           | _, _ => false end) args args' = true <->
        PublicTypeRead.smap (symbol_table M) args =
        PublicTypeRead.smap (symbol_table M) args').
    { unfold PublicTypeRead.smap. induction args as [|[f t] args Tail]; intros [|[g u] rest];
        cbn [PublicTypeRead.smap map fst snd]; try (split; congruence).
      rewrite !andb_true_iff, Nat.eqb_eq, IH, Tail.
      split; [intros [[-> ->] ->]; reflexivity | intro E; injection E; auto]. }
    rewrite andb_true_iff, Nat.eqb_eq, Rows.
    split; [intros [-> ->]; reflexivity | intro E; injection E; auto].
  - assert (Members : forall ns,
        (fix go (xs ys : list ty) :=
           match xs, ys with
           | [], [] => true
           | t :: rest, u :: tail => ty_eqb_with (same_classb M) t u && go rest tail
           | _, _ => false end) ms ns = true <->
        map (app_subst (symbol_table M)) ms = map (app_subst (symbol_table M)) ns).
    { induction ms as [|t ms Tail]; intros [|u rest]; cbn; try (split; congruence).
      rewrite andb_true_iff, IH, Tail.
      split; [intros [-> ->]; reflexivity | intro E; injection E; auto]. }
    rewrite Members. split; congruence.
Qed.

Theorem merge_eqb_spec : forall M, Solved M -> forall t u,
  merge_eqb M t u = true <-> MergeEq M t u.
Proof.
  intros M S t u. unfold merge_eqb.
  rewrite (@merge_ty_eqb_read M (proj1 S)), <- !section_table_read.
  symmetry. apply merge_section_kernel, section_table_is_section. exact S.
Qed.

Lemma symbol_preserves_outer : forall M t,
  type_outer (app_subst (symbol_table M) t) = type_outer t.
Proof.
  intros M [m|fs| |x|n args|ms];
    rewrite ?symbol_at_read, ?PublicTypeRead.subst_record, ?PublicTypeRead.subst_nom,
      ?PublicTypeRead.subst_union;
    try unfold PublicTypeRead.smap; cbn [type_outer]; try reflexivity;
    rewrite map_map; reflexivity.
Qed.

Theorem expand_outer : forall M, Solved M -> forall t u, MergeEq M t u ->
  type_outer (expand M t) = type_outer (expand M u).
Proof.
  intros M S t u E.
  apply (merge_section_kernel (section_table_is_section S)) in E.
  rewrite !section_table_read in E.
  rewrite <- (symbol_preserves_outer M (expand M t)).
  rewrite <- (symbol_preserves_outer M (expand M u)). now rewrite E.
Qed.

Lemma symbol_reads_children : forall M t,
  type_children (app_subst (symbol_table M) t) =
  map (app_subst (symbol_table M)) (type_children t).
Proof.
  intros M [m|fs| |x|n args|ms];
    rewrite ?symbol_at_read, ?PublicTypeRead.subst_record, ?PublicTypeRead.subst_nom,
      ?PublicTypeRead.subst_union;
    try unfold PublicTypeRead.smap; cbn [type_children]; try reflexivity;
    rewrite !map_map; reflexivity.
Qed.

Theorem expand_children : forall M, Solved M -> forall t u, MergeEq M t u ->
  Forall2 (MergeEq M) (type_children (expand M t)) (type_children (expand M u)).
Proof.
  intros M S t u E.
  apply (merge_section_kernel (section_table_is_section S)) in E.
  rewrite !section_table_read in E.
  assert (Children := f_equal type_children E). rewrite !symbol_reads_children in Children.
  apply mapped_list_eq in Children.
  induction Children as [|v w vs ws Eq _ IH]; constructor; [|exact IH].
  eapply METrans; [apply symbol_read |]. rewrite Eq. apply MESym, symbol_read.
Qed.

Theorem item_eqbM_spec : forall M, Solved M -> forall k k',
  item_eqbM M k k' = true <-> KeyEq M k k'.
Proof.
  intros M S k k'. destruct k, k'; cbn [item_eqbM item_eqb KeyEq provision_id];
    try (rewrite Nat.eqb_eq; split; congruence); try (split; congruence).
  rewrite andb_true_iff, Nat.eqb_eq, (merge_eqb_spec S). reflexivity.
Qed.

Theorem ilookM_key : forall A M, Solved M ->
  forall k k', KeyEq M k k' -> forall (l : list (item * A)), ilookM M k l = ilookM M k' l.
Proof.
  intros A M S k k' E l.
  apply (section_key_eq (section_table_is_section S)) in E.
  induction l as [|[j a] rest IH]; [reflexivity |]. cbn [ilookM].
  assert (B : item_eqbM M k j = item_eqbM M k' j).
  { apply eq_true_iff_eq. rewrite !item_eqbM_spec by exact S.
    rewrite !(section_key_eq (section_table_is_section S)). now rewrite E. }
  rewrite B. destruct (item_eqbM M k' j); [reflexivity | exact IH].
Qed.

Lemma merge_symbol_from_member : forall M c x,
  In c M -> In x (mc_members c) -> In x (merge_symbols M).
Proof.
  intros M c x C X. unfold merge_symbols. apply in_flat_map.
  exists c. split; [exact C | apply in_or_app; left; exact X].
Qed.

Lemma merge_symbol_from_shape : forall M c t,
  In c M -> mc_shape c = Some t -> incl (gens t) (merge_symbols M).
Proof.
  intros M c t C Sh x X. unfold merge_symbols. apply in_flat_map.
  exists c. split; [exact C | apply in_or_app; right; now rewrite Sh].
Qed.

Lemma shape_table_range : forall M n x t,
  In (x,t) (shape_table M n) -> incl (gens t) (merge_symbols M).
Proof.
  intros M n. induction n as [|n IH]; intros x t I; [contradiction |].
  apply shape_pair in I as (c & u & C & X & Sh & ->).
  eapply PublicCallRealize.subst_scoped; [exact IH |].
  eapply merge_symbol_from_shape; eassumption.
Qed.

Lemma symbol_table_range : forall M x t,
  In (x,t) (symbol_table M) -> incl (gens t) (merge_symbols M).
Proof.
  intros M x t I. apply symbol_pair in I as (c & h & rest & C & Members & X & ->).
  intros y [<-|[]]. eapply merge_symbol_from_member; [exact C |].
  rewrite Members. left. reflexivity.
Qed.

Lemma section_table_support : forall M x t,
  In (x,t) (section_table M) -> In x (merge_symbols M) /\ incl (gens t) (merge_symbols M).
Proof.
  intros M x t I. unfold section_table in I. apply in_map_iff in I as [[y v] [E I]].
  cbn [fst] in E. injection E as <- <-.
  apply symbol_pair in I as (c & h & rest & C & Members & X & _).
  assert (X' : In y (merge_symbols M)) by (eapply merge_symbol_from_member; eassumption).
  split; [exact X' | unfold expand].
  eapply PublicCallRealize.subst_scoped; [apply symbol_table_range |].
  eapply PublicCallRealize.subst_scoped; [apply shape_table_range |].
  intros z [<-|[]]. exact X'.
Qed.

Lemma section_table_function : forall M x t,
  In (x,t) (section_table M) -> lookup_subst x (section_table M) = Some t.
Proof.
  intros M x t I. unfold section_table in I |- *.
  apply in_map_iff in I as [[y v] [E I]]. cbn [fst] in E. injection E as <- <-.
  rewrite (@lookup_map_domain (fun z => app_subst (symbol_table M) (expand M (TAbs z))) _ y).
  assert (J : In y (map fst (symbol_table M))).
  { apply in_map_iff. exists (y,v). auto. }
  pose proof (PublicCallRealize.lookup_subst_in y _ J) as L.
  destruct (lookup_subst y (symbol_table M)); [reflexivity | contradiction].
Qed.

Theorem merge_has_mgm : forall es M, MergeOf es M ->
  exists s, MostGeneralMerge s es /\ SectionOf M s.
Proof.
  intros es M Form. exists (section_table M).
  assert (Section : SectionOf M (section_table M))
    by (apply section_table_is_section; exact (proj1 Form)).
  split; [|exact Section].
  eapply section_is_most_general; [exact Form | exact Section | | apply section_table_function].
  intros x t I. apply section_table_support in I as [Domain Range].
  pose proof (proj1 (proj2 (proj2 Form))) as Support.
  split; [apply Support; exact Domain |].
  intros y Y. apply Support, Range. exact Y.
Qed.
