(* The equality generated by merge classes and its substitution semantics. *)
From Stdlib Require Import List Arith Bool Relations RelationClasses.
From NM Require Import Audit.
From NM Require PublicTypeRead.
Import Audit.Semantics Audit.Semantics.Elaboration ListNotations.
Set Implicit Arguments.

Global Instance merge_eq_equivalence M : Equivalence (MergeEq M).
Proof.
  split.
  - exact (@MERefl M).
  - exact (@MESym M).
  - exact (@METrans M).
Qed.

(* Composition acts through the same template as MECong. *)
Definition compose (outer inner : subst) : subst :=
  map (fun q => (fst q, app_subst outer (snd q))) inner ++ outer.

Lemma compose_abs : forall outer inner x,
  app_subst (compose outer inner) (TAbs x) =
  app_subst outer (app_subst inner (TAbs x)).
Proof.
  intros outer inner. induction inner as [|[y t] inner IH]; intro x.
  - reflexivity.
  - cbn [compose map app app_subst lookup_subst fst snd].
    destruct (Nat.eqb x y); [reflexivity | apply IH].
Qed.

Lemma compose_read : forall outer inner t,
  app_subst (compose outer inner) t = app_subst outer (app_subst inner t).
Proof.
  intros outer inner t.
  rewrite <- (PublicTypeRead.app_subst_nil t) at 1.
  apply PublicTypeRead.subst2_agree. intros x _. apply compose_abs.
Qed.

Theorem merge_eq_substitute : forall M N s,
  Respects M s N -> forall t u, MergeEq M t u ->
    MergeEq N (app_subst s t) (app_subst s u).
Proof.
  intros M N s [Members Shapes] t u H. induction H.
  - apply MERefl.
  - apply MESym. assumption.
  - eapply METrans; eassumption.
  - eapply Members; eassumption.
  - eapply Shapes; eassumption.
  - rewrite <- !compose_read. apply MECong.
    intros x InX. rewrite !compose_abs. auto.
Qed.

Definition SolvesClasses (M : merge) (s : subst) : Prop :=
  (forall c x y, In c M -> In x (mc_members c) -> In y (mc_members c) ->
     app_subst s (TAbs x) = app_subst s (TAbs y)) /\
  (forall c x t, In c M -> In x (mc_members c) -> mc_shape c = Some t ->
     app_subst s (TAbs x) = app_subst s t).

Theorem merge_eq_sound : forall M s,
  SolvesClasses M s -> forall t u, MergeEq M t u -> app_subst s t = app_subst s u.
Proof.
  intros M s [Members Shapes] t u H. induction H.
  - reflexivity.
  - symmetry. assumption.
  - etransitivity; eassumption.
  - eapply Members; eassumption.
  - eapply Shapes; eassumption.
  - apply PublicTypeRead.subst2_agree. auto.
Qed.

Lemma merge_eq_read : forall M s,
  (forall x, MergeEq M (TAbs x) (app_subst s (TAbs x))) ->
  forall t, MergeEq M t (app_subst s t).
Proof.
  intros M s Reads t. rewrite <- (PublicTypeRead.app_subst_nil t) at 1.
  apply MECong. intros x _. apply Reads.
Qed.

Theorem merge_section_kernel : forall M s, SectionOf M s ->
  forall t u, MergeEq M t u <-> app_subst s t = app_subst s u.
Proof.
  intros M s [Read Constant] t u. split; [apply Constant |].
  intros Equal. eapply METrans; [apply merge_eq_read; exact Read |].
  rewrite Equal. apply MESym, merge_eq_read. exact Read.
Qed.

Lemma mapped_list_eq : forall A B (f : A -> B) xs ys,
  Forall2 (fun x y => f x = f y) xs ys <-> map f xs = map f ys.
Proof.
  intros A B f xs ys. split.
  - intro H. induction H; cbn; [reflexivity | congruence].
  - revert ys. induction xs as [|x xs IH]; intros [|y ys] Eq;
      cbn in Eq; try discriminate; constructor.
    + congruence.
    + apply IH. congruence.
Qed.

Lemma section_key_eq : forall M s, SectionOf M s ->
  forall k k', KeyEq M k k' <->
    app_subst_item s (provision_id k) = app_subst_item s (provision_id k').
Proof.
  intros M s Section k k'.
  destruct k; destruct k'; cbn [KeyEq provision_id app_subst_item map_snd];
    try (split; congruence).
  rewrite (merge_section_kernel Section). split.
  - intros [-> ->]. reflexivity.
  - intro E. injection E. auto.
Qed.

Lemma section_sig_eq : forall M s, SectionOf M s ->
  forall g g', SigEq M g g' <-> sig_subst s g = sig_subst s g'.
Proof.
  intros M s Section [ps t] [ps' t']. unfold SigEq, sig_subst. cbn.
  rewrite (merge_section_kernel Section).
  assert (Params : Forall2 (MergeEq M) ps ps' <->
                   map (app_subst s) ps = map (app_subst s) ps').
  { rewrite <- mapped_list_eq. split; intro F; induction F;
      constructor; try assumption; apply (merge_section_kernel Section); assumption. }
  rewrite Params. split.
  - intros [-> ->]. reflexivity.
  - intro E. injection E. auto.
Qed.

Lemma section_inst_eq : forall M s, SectionOf M s ->
  forall a b, InstEq M a b <->
    map (fun q => (fst q, app_subst s (snd q))) a =
    map (fun q => (fst q, app_subst s (snd q))) b.
Proof.
  intros M s Section a b. unfold InstEq. rewrite <- mapped_list_eq.
  split; intro F; induction F; constructor; try assumption.
  - destruct H as [Keys Values]. cbn. rewrite Keys, (proj1 (merge_section_kernel Section _ _) Values).
    reflexivity.
  - cbn in H. injection H as Keys Values. split; [exact Keys |].
    apply (merge_section_kernel Section). exact Values.
Qed.

Lemma option_eq_map : forall A B (R : A -> A -> Prop) (f : A -> B),
  (forall x y, R x y <-> f x = f y) ->
  forall a b, OptionEq R a b <-> option_map f a = option_map f b.
Proof.
  intros A B R f Equiv [a|] [b|]; cbn [OptionEq option_map].
  - rewrite Equiv. split; congruence.
  - split; [contradiction | discriminate].
  - split; [contradiction | discriminate].
  - split; auto.
Qed.

Lemma entry_key_raw : forall s e,
  entry_key s e = option_map (app_subst_item s) (raw_entry_key e).
Proof. intros s []; reflexivity. Qed.

Lemma entry_sig_raw : forall s e,
  entry_sig s e = option_map (sig_subst s) (raw_entry_sig e).
Proof. intros s []; reflexivity. Qed.

Lemma entry_inst_raw : forall s e,
  entry_inst s e = option_map (map (fun q => (fst q, app_subst s (snd q)))) (raw_entry_inst e).
Proof.
  intros s []; unfold entry_inst, raw_entry_inst, inst_read, read_inst; cbn;
    try reflexivity; rewrite map_map; reflexivity.
Qed.

Lemma raw_key_identity : forall e k, raw_entry_key e = Some k -> provision_id k = k.
Proof. intros [] k E; cbn in E; try discriminate; injection E as <-; reflexivity. Qed.

Theorem section_unifies : forall M s es, SectionOf M s ->
  (UnifiesMerge M es <-> Unifies s es).
Proof.
  intros M s es Section. unfold UnifiesMerge, Unifies.
  split; intros [Pairs Equations]; split.
  - intros e e' k InE InE' K K'. rewrite entry_key_raw in K, K'.
    destruct (raw_entry_key e) as [r|] eqn:R; [|discriminate].
    destruct (raw_entry_key e') as [r'|] eqn:R'; [|discriminate].
    injection K as <-. injection K' as Equal.
    assert (Keys : KeyEq M r r').
    { apply (section_key_eq Section). rewrite (raw_key_identity _ R), (raw_key_identity _ R').
      symmetry. exact Equal. }
    destruct (Pairs e e' r r' InE InE' R R' Keys) as [Sigs Insts].
    split.
    + rewrite !entry_sig_raw. apply option_eq_map with (R := SigEq M);
        [apply section_sig_eq; assumption | exact Sigs].
    + rewrite !entry_inst_raw. apply option_eq_map with (R := InstEq M);
        [apply section_inst_eq; assumption | exact Insts].
  - intros l r I. apply (merge_section_kernel Section). apply Equations. exact I.
  - intros e e' r r' InE InE' R R' Keys.
    apply (section_key_eq Section) in Keys.
    rewrite (raw_key_identity _ R), (raw_key_identity _ R') in Keys.
    assert (K : entry_key s e = Some (app_subst_item s r)) by (rewrite entry_key_raw, R; reflexivity).
    assert (K' : entry_key s e' = Some (app_subst_item s r)) by (rewrite entry_key_raw, R', Keys; reflexivity).
    destruct (Pairs e e' _ InE InE' K K') as [Sigs Insts].
    split.
    + apply option_eq_map with (f := sig_subst s);
        [apply section_sig_eq; assumption | rewrite <- !entry_sig_raw; exact Sigs].
    + apply option_eq_map with (f := map (fun q => (fst q, app_subst s (snd q))));
        [apply section_inst_eq; assumption | rewrite <- !entry_inst_raw; exact Insts].
  - intros l r I. apply (merge_section_kernel Section). apply Equations. exact I.
Qed.

(* Principality gives the forward implication directly. Any section is a
   separating unifier, which supplies the reverse implication. *)
Theorem merge_semantic_reading_with_section : forall es M s,
  MergeOf es M -> SectionOf M s ->
  forall t u, MergeEq M t u <-> forall r, Unifies r es -> app_subst r t = app_subst r u.
Proof.
  intros es M s [_ [_ [_ [UnifiesM Principal]]]] Section t u. split.
  - intros E r U. exact (Principal r U t u E).
  - intro All. apply (merge_section_kernel Section). apply All.
    apply (section_unifies es Section). exact UnifiesM.
Qed.

Theorem section_is_most_general : forall es M s,
  MergeOf es M -> SectionOf M s ->
  (forall g t, In (g, t) s -> In g (flat_map entry_gens es) /\ incl (gens t) (flat_map entry_gens es)) ->
  (forall g t, In (g, t) s -> lookup_subst g s = Some t) ->
  MostGeneralMerge s es.
Proof.
  intros es M s [_ [_ [_ [UnifiesM Principal]]]] [Read Constant] Support Functional.
  assert (Section : SectionOf M s) by (split; assumption).
  split; [apply (section_unifies es Section); exact UnifiesM |].
  split.
  - intro t. symmetry. apply Constant, merge_eq_read. exact Read.
  - split; [|split; assumption]. intros r U t. symmetry. apply Principal.
    + exact U.
    + apply merge_eq_read. exact Read.
Qed.
