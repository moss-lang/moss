def byte_values():
    return [(f"x{value:02x}", value) for value in range(256)]


def byte_class(value):
    ranges = [
        (0x00, 0x7F, "Ascii"),
        (0x80, 0x8F, "Cont808F"),
        (0x90, 0x9F, "Cont909F"),
        (0xA0, 0xBF, "ContA0BF"),
        (0xC2, 0xDF, "Lead2"),
        (0xE0, 0xE0, "LeadE0"),
        (0xE1, 0xEC, "LeadE1EC_EEEF"),
        (0xED, 0xED, "LeadED"),
        (0xEE, 0xEF, "LeadE1EC_EEEF"),
        (0xF0, 0xF0, "LeadF0"),
        (0xF1, 0xF3, "LeadF1F3"),
        (0xF4, 0xF4, "LeadF4"),
    ]
    return next((name for first, last, name in ranges if first <= value <= last), "Invalid")


def gen_spell():
    lines = [
        f"""import "./bytes.moss" use push_string;

# The strings the compiler must hold itself.
#
# A Wasm module names its imports and exports in its own bytes, so an
# emitter cannot avoid knowing how `wasi_snapshot_preview1` is spelled,
# and the back end cannot recognize `I32` or `i32_bool` without knowing
# how those are spelled either. Each helper appends its quoted spelling to
# the byte buffer; binary emission continues to work in byte values.
#
{HEADER}

assume Std {{"""
    ]
    for name in SPELLED:
        function = "sp_" + name.replace(".", "_").lstrip("_")
        lines.append(
            f"  fn {function}(out: IntList) {{\n    push_string(out, {json.dumps(name)});\n  }}\n"
        )
    return "\n".join([*lines, "}", ""])


def snake(name):
    if name in ("LParen", "RParen", "LBracket", "RBracket", "LBrace", "RBrace"):
        return name.lower()
    return re.sub(r"(?<!^)[A-Z]", lambda found: "_" + found[0], name).lower()


def gen_token_codes():
    source = (ROOT / "src/lex.moss").read_text()
    declaration = source.split("type Token =", 1)[1].split(";", 1)[0]
    names = [part.strip() for part in declaration.split("|") if part.strip()]
    lines = [
        f"""import "./bytes.moss" use *;
import "./lex.moss" use Token;
import "./token.moss" use *;

# Token kinds as Ints.
#
# `Token` is a union of sixty units, which is the right type for the
# lexer to return and the wrong one for a recursive-descent parser to
# carry: a parser compares the current token against a handful of
# expected ones per production, and a match arm per comparison is
# unreadable. The cursor holds an Int instead, converted here once per
# token.
#
{HEADER}

assume Std {{"""
    ]
    lines.extend(f"  fn tk_{snake(name)}(): Int {{ {index} }}" for index, name in enumerate(names))
    lines.extend(["", "  fn token_code(t: Token): Int {", "    match t {"])
    lines.extend(f"      {name} => tk_{snake(name)}()," for name in names)
    return "\n".join([*lines, "    }", "  }", "}", ""])


